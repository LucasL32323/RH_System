-- LIMPEZA (permite rodar o script mais de uma vez)
-- ============================================================

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS BENEFICIOS_FUNCIONARIOS;
DROP TABLE IF EXISTS BENEFICIOS;
DROP TABLE IF EXISTS FORMULARIO_RESPOSTAS;
DROP TABLE IF EXISTS FORMULARIO_PERGUNTAS;
DROP TABLE IF EXISTS FORMULARIO;
DROP TABLE IF EXISTS TREINAMENTO_CERTIFICADO;
DROP TABLE IF EXISTS TREINAMENTO_FUNCIONARIO;
DROP TABLE IF EXISTS TREINAMENTO;
DROP TABLE IF EXISTS BANCO_HORAS;
DROP TABLE IF EXISTS ADVERTENCIA;
DROP TABLE IF EXISTS HOLERITE;
DROP TABLE IF EXISTS MANUTENCAO_PONTO;
DROP TABLE IF EXISTS PONTO;
DROP TABLE IF EXISTS AVISOS_VISUALIZACOES;
DROP TABLE IF EXISTS AVISOS;
DROP TABLE IF EXISTS USUARIO;
DROP TABLE IF EXISTS FUNCIONARIOS_DETALHES;
DROP TABLE IF EXISTS FUNCIONARIOS;
DROP TABLE IF EXISTS GESTORES;
DROP TABLE IF EXISTS SETORES;
DROP TABLE IF EXISTS CARGO;
DROP TABLE IF EXISTS NIVEIS_DE_ACESSO;

SET FOREIGN_KEY_CHECKS = 1;

-- ============================================================
-- 1. NIVEIS_DE_ACESSO
-- ============================================================

CREATE TABLE NIVEIS_DE_ACESSO (
    ID_NV_ACESSO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255)
) ENGINE=InnoDB;

-- ============================================================
-- 2. CARGO
-- ============================================================

CREATE TABLE CARGO (
    ID_CARGO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_CARGO VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),
    CARGA_HORARIA DECIMAL(5,2)
) ENGINE=InnoDB;

-- ============================================================
-- 3. FUNCIONARIOS
-- ============================================================
-- A FK de ID_GESTOR é criada no item 6, porque FUNCIONARIOS
-- e GESTORES dependem uma da outra.

CREATE TABLE FUNCIONARIOS (
    ID_FUNCIONARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    DATA_NASCIMENTO DATE,
    DATA_ADMISSAO DATE NOT NULL,
    DATA_DESLIGAMENTO DATE,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    EMAIL VARCHAR(150),
    TELEFONE VARCHAR(30),
    ID_CARGO INT,
    ID_SETOR INT,
    ID_GESTOR INT,
    ID_NV_ACESSO INT,

    CONSTRAINT FK_FUNCIONARIO_CARGO
        FOREIGN KEY (ID_CARGO)
        REFERENCES CARGO(ID_CARGO),

    CONSTRAINT FK_FUNCIONARIO_NIVEL_ACESSO
        FOREIGN KEY (ID_NV_ACESSO)
        REFERENCES NIVEIS_DE_ACESSO(ID_NV_ACESSO)
) ENGINE=InnoDB;

-- ============================================================
-- 4. SETORES
-- ============================================================
-- Mesmo caso de FUNCIONARIOS: a FK de ID_GESTOR entra no item 6.

CREATE TABLE SETORES (
    ID_SETOR INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),
    ID_GESTOR INT
) ENGINE=InnoDB;

-- ============================================================
-- 5. GESTORES
-- ============================================================

CREATE TABLE GESTORES (
    ID_GESTOR INT AUTO_INCREMENT PRIMARY KEY,
    ID_FUNCIONARIO INT NOT NULL,
    ID_SETOR INT,
    ID_NV_ACESSO INT,

    CONSTRAINT FK_GESTOR_FUNCIONARIO
        FOREIGN KEY (ID_FUNCIONARIO)
        REFERENCES FUNCIONARIOS(ID_FUNCIONARIO),

    CONSTRAINT FK_GESTOR_SETOR
        FOREIGN KEY (ID_SETOR)
        REFERENCES SETORES(ID_SETOR),

    CONSTRAINT FK_GESTOR_NIVEL_ACESSO
        FOREIGN KEY (ID_NV_ACESSO)
        REFERENCES NIVEIS_DE_ACESSO(ID_NV_ACESSO)
) ENGINE=InnoDB;

-- ============================================================
-- 6. FKs entre FUNCIONARIOS, SETORES e GESTORES
-- ============================================================

ALTER TABLE FUNCIONARIOS
    ADD CONSTRAINT FK_FUNCIONARIO_GESTOR
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTORES(ID_GESTOR);

ALTER TABLE FUNCIONARIOS
    ADD CONSTRAINT FK_FUNCIONARIO_SETOR
        FOREIGN KEY (ID_SETOR)
        REFERENCES SETORES(ID_SETOR);

ALTER TABLE SETORES
    ADD CONSTRAINT FK_SETOR_GESTOR
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTORES(ID_GESTOR);

-- ============================================================
-- 7. FUNCIONARIOS_DETALHES
-- ============================================================

CREATE TABLE FUNCIONARIOS_DETALHES (
    ID_FUNCIONARIO_DETALHES INT AUTO_INCREMENT PRIMARY KEY,
    ID_FUNCIONARIO INT NOT NULL,
    NOME VARCHAR(150),
    DATA_NASCIMENTO DATE,
    DATA_ADMISSAO DATE,
    DATA_DESLIGAMENTO DATE,
    ATIVO BOOLEAN DEFAULT TRUE,
    EMAIL VARCHAR(150),
    TELEFONE VARCHAR(30),
    ID_CARGO INT,
    ID_NV_ACESSO INT,
    ID_GESTOR INT,

    CONSTRAINT FK_DETALHES_FUNCIONARIO
        FOREIGN KEY (ID_FUNCIONARIO)
        REFERENCES FUNCIONARIOS(ID_FUNCIONARIO),

    CONSTRAINT FK_DETALHES_CARGO
        FOREIGN KEY (ID_CARGO)
        REFERENCES CARGO(ID_CARGO),

    CONSTRAINT FK_DETALHES_NIVEL
        FOREIGN KEY (ID_NV_ACESSO)
        REFERENCES NIVEIS_DE_ACESSO(ID_NV_ACESSO),

    CONSTRAINT FK_DETALHES_GESTOR
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTORES(ID_GESTOR)
) ENGINE=InnoDB;

-- ============================================================
-- 8. USUARIO
-- ============================================================

CREATE TABLE USUARIO (
    ID_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
    ID_FUNCIONARIO INT NOT NULL,
    NOME VARCHAR(150) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL,
    SENHA VARCHAR(255) NOT NULL,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
